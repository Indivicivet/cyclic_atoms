"""Generate explicit batches and Lean-checked synthesis certificates."""

import json
from itertools import combinations
from pathlib import Path

import chemistry.closed_reactions as closed
import chemistry.synthesis as synthesis
import visualization.core as core


def derivation(feeds, channels):
    """Choose finite production trees, then order their channels topologically.

    Tree cost is an upper bound on events, not an optimal synthesis claim.
    Keeping trees small also keeps the checked certificates compact.
    """
    costs = {m: 0 for m in feeds}
    producers = {}
    while True:
        changed = False
        for i, (left, right) in enumerate(channels):
            for inputs, outputs in ((left, right), (right, left)):
                if all(m in costs for m in inputs):
                    cost = 1 + sum(costs[m] for m in inputs)
                    for molecule in outputs:
                        if molecule not in costs or cost < costs[molecule]:
                            costs[molecule] = cost
                            producers[molecule] = i
                            changed = True
        if not changed:
            break
    available = set(feeds)
    plan = []
    for molecule in sorted(costs, key=costs.__getitem__):
        if molecule not in available:
            i = producers[molecule]
            left, right = channels[i]
            inputs, outputs = (left, right) if set(left) <= available else (right, left)
            if not set(inputs) <= available:
                raise ValueError("production tree is not topologically ordered")
            available.update(outputs)
            plan.append(i)
    return available, plan


def lean_formula(molecule):
    return "(Formula.mk " + " ".join(map(str, molecule)) + ")"


def lean_list(items):
    return "[" + ", ".join(items) + "]"


def write_tree_certificates(root, species):
    """Give Lean parent/rank witnesses; Lean verifies all edges independently."""
    lines = [
        "import CyclicAtoms.GridWitness",
        "",
        "/- Generated by chemistry/universal_synthesis.py. -/",
        "namespace CyclicAtoms.Geometry",
        "",
        "def treeCertificates357 : List TreeCertificate := [",
    ]
    for atoms in species.values():
        sites = [set(core.sites(atom)) for atom in atoms]
        parents = {0: 0}
        ranks = [0] * len(atoms)
        queue = [0]
        # List iteration visits appended vertices, giving a FIFO traversal.
        for i in queue:
            for j in range(len(atoms)):
                if j not in parents and sites[i] & sites[j]:
                    parents[j] = i
                    ranks[j] = ranks[i] + 1
                    queue.append(j)
        if len(parents) != len(atoms):
            raise ValueError("grid witness has no spanning tree")
        lines.append(
            "  TreeCertificate.mk "
            + lean_list(map(str, ranks))
            + " "
            + lean_list(str(parents[i]) for i in range(len(atoms)))
            + ","
        )
    lines += ["]", "", "end CyclicAtoms.Geometry", ""]
    (root / "lean/CyclicAtoms/GeometryWitnessData.lean").write_text(
        "\n".join(lines).replace(",\n]", "\n]"), encoding="utf-8"
    )


def write_lean(root, species, reactions, batches, feeds):
    lines = [
        "import CyclicAtoms.Chemistry",
        "",
        "/- Generated by chemistry/universal_synthesis.py. Finite certificates",
        "are checked in Chemistry357.lean using Lean's native_decide. -/",
        "",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 0",
        "",
        "namespace CyclicAtoms.Chemistry",
        "",
        "def formulas357 : List Formula := [",
    ]
    lines += ["  " + lean_formula(m) + "," for m in species]
    lines += [
        "]",
        "",
        "def formulaAt357 (i : Nat) : Formula := formulas357.getD i ⟨0, 0, 0⟩",
        "",
        "def reactionTable357 : List Reaction := [",
    ]
    for left, right in reactions:
        lines.append(
            "  Reaction.mk "
            + lean_list(map(lean_formula, left))
            + " "
            + lean_list(map(lean_formula, right))
            + ","
        )
    lines += ["]", ""]
    for i, atoms in enumerate(species.values()):
        indices = [{3: 0, 5: 35, 7: 56}[p] + int(phase * 105) for p, phase, _ in atoms]
        lines += [
            f"def gridWitness357_{i} : List Line := " + lean_list(map(str, indices)),
            "",
        ]
    lines += ["def gridWitnesses357 : List (List Line) := ["]
    lines += [f"  gridWitness357_{i}," for i in range(len(species))]
    lines += ["]", "", "def feedPairs357 : List (List Formula) := ["]
    lines += ["  " + lean_list(map(lean_formula, pair)) + "," for pair in feeds]
    lines += ["]", ""]
    reaction_ids = {reaction: i for i, reaction in enumerate(reactions)}
    formula_ids = {m: i for i, m in enumerate(species)}
    for p, pair in enumerate(batches):
        for i, result in enumerate(pair):
            initial = tuple(
                str(formula_ids[m])
                for m, n in result["batch"]["initial"]
                for _ in range(n)
            )
            lines += [
                f"def batch357_{p}_{i} : Plan := Plan.mk (("
                + lean_list(initial)
                + " : List Nat).map formulaAt357) "
                + lean_list(str(reaction_ids[step]) for step in result["steps"]),
                "",
            ]
    lines += ["def batchCertificates357 : List (List Plan) := ["]
    for p, pair in enumerate(batches):
        lines.append(
            "  " + lean_list(f"batch357_{p}_{i}" for i in range(len(pair))) + ","
        )
    lines += [
        "]",
        "",
        "def formula357 (i : Fin 86) : Formula :=",
        "  formulaAt357 i.val",
        "",
        "def feedPair357 (i : Fin 3) : List Formula := feedPairs357.getD i.val []",
        "",
        "def certificate357 (p : Fin 3) (i : Fin 86) : Plan :=",
        "  (batchCertificates357.getD p.val []).getD i.val ⟨[], []⟩",
        "",
        "theorem catalog_length357 : formulas357.length = 86 := by decide",
        "",
        "def witnessChecks357 (i : Fin 86) : Bool :=",
        "  moleculeOnGrid (gridWitnesses357.getD i.val []) &&",
        "    decide (gridFormula (gridWitnesses357.getD i.val []) = formula357 i)",
        "",
        "theorem witness_checks357 : allFinCheck 86 witnessChecks357 = true := by native_decide",
        "",
        "/-- Every catalog entry has a paired, connected 105-site grid witness. -/",
        "theorem catalog_witnesses357 (i : Fin 86) :",
        "    moleculeOnGrid (gridWitnesses357.getD i.val []) = true ∧",
        "    gridFormula (gridWitnesses357.getD i.val []) = formula357 i := by",
        "  have h := allFinCheck_sound 86 witnessChecks357 witness_checks357 i",
        "  exact ⟨and_left_true _ _ h, of_decide_eq_true (and_right_true _ _ h)⟩",
        "",
        "def batchChecks357 (p : Fin 3) (i : Fin 86) : Bool :=",
        "  checkPlan formulas357 reactionTable357 (feedPair357 p) (formula357 i)",
        "    (certificate357 p i)",
        "",
        "theorem certificate_checks357 :",
        "    allFinCheck 3 (fun p => allFinCheck 86 (batchChecks357 p)) = true := by native_decide",
        "",
        "/-- Independently check every step, all feed supplies, and all target copies. -/",
        "theorem certificates_valid357 (p : Fin 3) (i : Fin 86) :",
        "    checkPlan formulas357 reactionTable357 (feedPair357 p) (formula357 i)",
        "      (certificate357 p i) = true :=",
        "  allFinCheck_sound 86 (batchChecks357 p)",
        "    (allFinCheck_sound 3 _ certificate_checks357 p) i",
        "",
        "theorem reactions_are_two_to_two357 :",
        "    reactionTable357.all (fun r => decide",
        "      (r.inputs.length = 2 ∧ r.outputs.length = 2)) = true := by decide",
        "",
        "theorem every_catalog_formula_synthesizable357 (p : Fin 3) (i : Fin 86) :",
        "    Synthesizable formulas357 reactionTable357 (feedPair357 p) (formula357 i) :=",
        "  ⟨certificate357 p i, certificates_valid357 p i⟩",
        "",
        "/-- The count formulas cover every positive three-element parity profile. -/",
        "theorem parity_formula_in_catalog357 :",
        "    ∀ a : Fin 2, ∀ b : Fin 6, ∀ c : Fin 8,",
        "      threeElements (parityFormula a b c) →",
        "      ∃ i : Fin 86, formula357 i = parityFormula a b c := by native_decide",
        "",
        "theorem every_parity_formula_synthesizable357 (p : Fin 3)",
        "    (a : Fin 2) (b : Fin 6) (c : Fin 8)",
        "    (h : threeElements (parityFormula a b c)) :",
        "    Synthesizable formulas357 reactionTable357 (feedPair357 p)",
        "      (parityFormula a b c) := by",
        "  match parity_formula_in_catalog357 a b c h with",
        "  | ⟨i, hi⟩ =>",
        "    rw [← hi]",
        "    exact every_catalog_formula_synthesizable357 p i",
        "",
        "#print axioms every_parity_formula_synthesizable357",
        "#print axioms parity_factorization",
        "",
        "end CyclicAtoms.Chemistry",
        "",
    ]
    # Separate data avoids re-elaborating the generated batches during proof edits.
    proof_start = lines.index(
        "theorem catalog_length357 : formulas357.length = 86 := by decide"
    )
    (root / "lean/CyclicAtoms/Chemistry357Data.lean").write_text(
        "\n".join(lines[:proof_start] + ["end CyclicAtoms.Chemistry", ""]).replace(
            ",\n]", "\n]"
        ),
        encoding="utf-8",
    )
    (root / "lean/CyclicAtoms/Chemistry357.lean").write_text(
        "\n".join(
            [
                "import CyclicAtoms.Chemistry357Data",
                "",
                "set_option maxRecDepth 100000",
                "set_option maxHeartbeats 0",
                "",
                "namespace CyclicAtoms.Chemistry",
                "",
            ]
            + lines[proof_start:]
        ),
        encoding="utf-8",
    )


def main():
    root = Path(__file__).resolve().parents[1]
    species = closed.catalog()
    channels = tuple(
        (left, right)
        for left, right in closed.reactions(species)
        if len(left) == len(right) == 2
    )
    feeds = tuple(combinations(synthesis.FEEDS, 2))
    batches = []
    used = set()
    for pair in feeds:
        available, plan = derivation(pair, channels)
        if available != set(species):
            raise ValueError(f"unreachable formulas: {set(species) - available}")
        results = []
        for target in species:
            _, steps = synthesis.expand_types(channels, plan, pair, target)
            batch = synthesis.audit(steps, pair, target)
            used.update(steps)
            results.append({"target": target, "steps": steps, "batch": batch})
        batches.append(results)
        print(
            "Supply",
            pair,
            "reaches",
            len(results),
            "formulas; longest certificate",
            max(len(r["steps"]) for r in results),
        )
    output = root / "chemistry/output/universal_synthesis.json"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        json.dumps({"feeds": feeds, "batches": batches}, indent=2) + "\n",
        encoding="utf-8",
    )
    write_lean(root, species, sorted(used), batches, feeds)
    write_tree_certificates(root, species)


if __name__ == "__main__":
    main()
